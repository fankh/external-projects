const START_B = 104
const STOP = '1100011101011'

/** Code 128-B 인코딩 → 바 폭 배열이 아닌 0/1 모듈 문자열 */
export function code128b(value: string): string {
  const codes: number[] = [START_B]
  for (const ch of value) {
    const v = ch.charCodeAt(0)
    // Code Set B: ASCII 32~126 → 값 0~94
    codes.push(v >= 32 && v <= 126 ? v - 32 : 0)
  }
  const checksum = codes.reduce((sum, c, i) => sum + (i === 0 ? c : c * i), 0) % 103
  codes.push(checksum)
  return codes.map((c) => CODE128_PATTERNS[c]).join('') + STOP
}

/** 모듈 문자열 → 인쇄용 SVG */
export function barcodeSvg(value: string, width = 220, height = 44): string {
  const modules = code128b(value)
  const mw = width / modules.length
  let x = 0
  const bars: string[] = []
  for (const m of modules) {
    if (m === '1') bars.push(`<rect x="${x.toFixed(3)}" y="0" width="${mw.toFixed(3)}" height="${height}" fill="#000"/>`)
    x += mw
  }
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${width} ${height}" width="${width}" height="${height}" shape-rendering="crispEdges">${bars.join('')}</svg>`
}
