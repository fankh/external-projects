/** 자유 입력이 나가는 출구의 길이 상한.
 *
 *  앱의 자유 입력(사유·비고·메모·제목·답변)에는 상한이 없다 — 화면의 input·textarea 92곳에
 *  maxLength 가 하나도 없고, 서버 액션 106곳도 trim 만 하고 길이를 보지 않는다. 서버 액션은
 *  화면을 거치지 않고도 호출되므로 상한을 화면에만 두는 것도 답이 아니다.
 *
 *  그런데 무한히 긴 문자열이 실제로 **무언가를 깨뜨리는** 자리는 두 곳뿐이고, 둘 다 단일 지점이다.
 *  입력 106곳을 각각 막는 대신 그 두 출구에서 자른다(한 곳에서 만든다).
 *
 *  - 엑셀 셀: ECMA-376 Part 1 §18.3.1.4 가 셀 문자열을 32,767자로 제한한다. 넘으면 Excel 이
 *    시트가 아니라 **워크북 전체**를 "복구할 수 없는 내용"으로 보고 열기를 거부한다 — 긴 사유
 *    한 줄 때문에 대장 반출본 전부를 못 읽는다.
 *  - 발송 제목: RFC 5322 §2.1.1 은 헤더 한 줄을 998옥텟으로 권고한다. 반려 사유가 제목에 통째로
 *    실리는 경로가 있어(결재 결과 통보) 사유 길이가 곧 제목 길이가 된다. 발송 이력 화면도 제목을
 *    한 줄로 그리므로 표가 통째로 밀린다.
 *
 *  자를 때는 잘렸다는 사실을 남긴다 — 말줄임표 없이 자르면 받는 사람이 온전한 값으로 읽는다. */

/** 엑셀 셀 문자열 상한 (ECMA-376 Part 1 §18.3.1.4). */
export const XLSX_CELL_MAX = 32_767

/** 발송 제목 상한. 시드·런타임이 만드는 정상 제목은 전부 이보다 훨씬 짧아(시드 최장 32자)
 *  이 상한에 닿는 것은 자유 입력이 그대로 실린 제목뿐이다. RFC 5322 권고(998옥텟)보다 넉넉히 아래로
 *  잡아 발송 이력 표가 한 줄에 들어가게 한다. */
export const SUBJECT_MAX = 300

/** 상한을 넘으면 말줄임표를 붙여 자른다. 결과 길이는 정확히 max 를 넘지 않는다.
 *  상한 이하면 원본을 그대로 돌려준다(정상 값은 손대지 않는다). */
export function ellipsize(s: string, max: number): string {
  if (max <= 0) return ''
  if (s.length <= max) return s
  return `${s.slice(0, max - 1)}…`
}

/** HTML 문서에 사람 입력을 꽂을 때의 이스케이프.
 *
 *  인쇄용 문서 라우트 10곳(자산 카드·계약 카드·인수인계서·검수 확인서·라벨·라벨 묶음·라이선스 카드·
 *  대여 확인서·분실 신고서·오프보딩 명세서)이 저마다 똑같은 한 줄을 복사해 두고 있었다. 지금은 열 벌이
 *  모두 같지만, 복사본이 열 개라는 사실 자체가 결함이다 — 새 문서 라우트가 하나만 빠뜨리면 모델명·비고·
 *  사유에 넣은 스크립트가 그대로 실행되는 저장형 XSS 가 되고, 빠뜨렸다는 것을 알려 줄 자리가 없다.
 *  한 곳에서 만들고, 스모크가 "모든 HTML 라우트가 이걸 쓴다"를 센다.
 *
 *  큰따옴표까지 바꾸는 이유 — 속성값 자리(title="...")에 그대로 꽂히는 곳이 있어 따옴표를 남기면
 *  속성을 닫고 새 속성을 열 수 있다. 작은따옴표는 이 문서들이 속성 인용에 쓰지 않는다. */
export function escHtml(v: string): string {
  return String(v).replace(/[&<>"]/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' })[c] as string)
}
